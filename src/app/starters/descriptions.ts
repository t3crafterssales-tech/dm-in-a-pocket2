/** "Versatile", "Two-handed" or "One-handed", from the SRD's properties. */
export function handlingOf(properties: string): string {
  const p = properties.toLowerCase();
  if (p.includes("versatile")) return "Versatile";
  if (p.includes("two-handed")) return "Two-handed";
  return "One-handed";
}
